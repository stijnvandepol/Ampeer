def test_a_measurement_outside_the_window_is_ignored_by_the_fit(client: Any) -> None:
    """Backfill from another year must not move a figure about this one."""
    user = _register(client)
    link = _give_the_account_a_meter(user)
    QuarterReading.objects.create(
        link=link,
        measured_at=datetime(2022, 6, 1, 12, 0, tzinfo=UTC),
        consumption_kwh=99.0,
        feed_in_kwh=0.0,
    )

    check = client.post(
        "/api/auth/advice/", BODY, content_type="application/json", **_csrf(client)
    ).json()["consumption_check"]

    assert check is not None
    assert check["p50_kwh"] == pytest.approx(TRUE_ANNUAL_KWH, rel=0.02)
