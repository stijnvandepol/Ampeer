SYSTEM = PVSystem(peak_power_wp=3500, azimuth_deg=0.0, tilt_deg=35.0)


class FlatProfiles:
    def fractions(self, year: int, category: ProfileCategory) -> np.ndarray:
        grid = YearGrid.for_year(year)
        return np.full(grid.quarters, 1.0 / grid.quarters)


@pytest.fixture(autouse=True)
def _offline_providers(monkeypatch: pytest.MonkeyPatch) -> None:
    """PVGIS and the NEDU file replaced on both paths that reach them.

    Two patches and not one. `advice.service` imported these names for the
    advice itself and `accounts.calibration` imported them for the fit, so
    patching either alone leaves the other reading a 13 MB CSV this test does
    not ship and calling a host this project refuses to call from a test.
    """

    def profiles() -> FlatProfiles:
        return FlatProfiles()

    def production(weather_year: int) -> FallbackProvider:
        return FallbackProvider(weather_year)

    for module in ("advice.service", "accounts.calibration"):
        monkeypatch.setattr(f"{module}.profile_provider", profiles)
        monkeypatch.setattr(f"{module}.production_provider", production)


def _csrf(client: Any) -> dict[str, str]:
    client.get("/api/auth/me/")
    return {"HTTP_X_CSRFTOKEN": client.cookies["csrftoken"].value}


def _register(client: Any, email: str = EMAIL) -> User:
    response = client.post(
        "/api/auth/register/",
        {
            "email": email,
            "password": TEST_PASSWORD,
            "consent_meter_link": True,
            "consent_lead_generation": False,
            "text_version": CONSENT_TEXT_VERSION,
        },
        content_type="application/json",
        **_csrf(client),
    )
    assert response.status_code == 201, response.content
    return User.objects.get(email=email)


def _year_import(annual_kwh: float) -> tuple[np.ndarray, np.ndarray]:
    household = Household(
        postcode4="5401", annual_consumption_kwh=annual_kwh, daytime_occupancy=False
    )
    hourly, temperature, _ = FallbackProvider(WEATHER_YEAR).hourly_series(
        household.postcode4, SYSTEM.azimuth_deg, SYSTEM.tilt_deg
    )
    production = production_series(hourly, SYSTEM, GRID, weather_year=WEATHER_YEAR)
    consumption = compose_consumption(
        household,
        GRID,
        FlatProfiles().fractions(GRID.year, household.profile_category),
        temperature,
        weather_year=WEATHER_YEAR,
        production_kwh=production,
    )
    flows = simulate(consumption, production)
    return flows.total_import, flows.total_export


def _give_the_account_a_meter(user: User, annual_kwh: float = TRUE_ANNUAL_KWH) -> MeterLink:
    """Eight weeks of readings ending now, generated by the model.

    THE TIMESTAMPS ARE THE POINT OF THIS FIXTURE. It used to lay the readings
    down from `grid_epoch(GRID)`, which is the first quarter of the profile
    year, 2025. Every test built on it passed, and no household could ever have
    produced that data: quarter readings are deleted after ninety days, so a
    quarter from 2025 cannot be in the table in 2026 at all. The fixture proved
    the machinery and never once asked whether the machinery could be reached.

    So the window is where a real one is, the eight weeks ending now, and each
    reading carries the modelled flow for the grid position it maps to. That
    keeps the data self consistent with the model, which is what lets the fit
    recover `annual_kwh`, while the path from a timestamp to a position is the
    one production actually walks.
    """
    user.email_verified_at = timezone.now()
    user.save(update_fields=["email_verified_at"])
    link, _ = service.link_meter(user)

    imported, exported = _year_import(annual_kwh)
    quarters = WINDOW_WEEKS * 7 * QUARTERS_PER_DAY
    # On a quarter boundary, because the ingest serializer refuses anything
    # else and a fixture that could not be pushed is not a fixture.
    last = timezone.now().replace(minute=0, second=0, microsecond=0)
    rows = []
    for step in range(quarters):
        measured_at = last - timedelta(minutes=15 * step)
        position = grid_position(measured_at, GRID)
        if position is None:
            continue  # 29 February, or a weekday shift over the year's edge
        rows.append(
            QuarterReading(
                link=link,
                measured_at=measured_at,
                consumption_kwh=float(imported[position]),
                feed_in_kwh=float(exported[position]),
            )
        )
    QuarterReading.objects.bulk_create(rows)
    return link


def test_an_advice_asked_for_through_a_session_belongs_to_that_account(client: Any) -> None:
    user = _register(client)

    response = client.post(
        "/api/auth/advice/", BODY, content_type="application/json", **_csrf(client)
    )

    assert response.status_code == 201, response.content
    stored = StoredAdvice.objects.get(token=response.json()["token"])
    assert stored.owner == user


def _advice(client: Any, body: dict[str, Any] | None = None) -> dict[str, Any]:
    response = client.post(
        "/api/auth/advice/",
        BODY if body is None else body,
        content_type="application/json",
        **_csrf(client),
    )
    assert response.status_code == 201, response.content
    return cast(dict[str, Any], response.json())


def _check(client: Any) -> dict[str, Any]:
    response = client.post(
        "/api/auth/advice/check/", content_type="application/json", **_csrf(client)
    )
    assert response.status_code == 200, response.content
    return cast(dict[str, Any], response.json())


def test_an_advice_does_not_pay_for_a_fit_nobody_asked_for(client: Any) -> None:
    """The advice route computes an advice and stops there."""
    _register(client)
    assert "consumption_check" not in _advice(client)


def test_without_a_meter_there_is_nothing_to_check(client: Any) -> None:
    """The advice is named anyway, because that is a different fact.

    An account with an advice and no meter and an account with neither both
    have nothing to show, and the page offers help in only one of those two
    cases, so the answer has to say which one it is.
    """
    _register(client)
    advice = _advice(client)

    answer = _check(client)

    assert answer["check"] is None
    assert answer["advice_token"] == advice["token"]


def test_without_an_advice_there_is_nothing_to_check(client: Any) -> None:
    """A fit needs a described household, and only an advice describes one."""
    user = _register(client)
    _give_the_account_a_meter(user)

    answer = _check(client)

    assert answer["check"] is None
    assert answer["advice_token"] is None


def test_a_meter_that_disagrees_is_reported_with_its_band(client: Any) -> None:
    user = _register(client)
    _give_the_account_a_meter(user)
    advice = _advice(client)

    answer = _check(client)

    assert answer["advice_token"] == advice["token"]
    check = answer["check"]
    assert check["typed_kwh"] == pytest.approx(TRUE_ANNUAL_KWH * 0.7)
    assert check["p50_kwh"] == pytest.approx(TRUE_ANNUAL_KWH, rel=0.02)
    assert check["p10_kwh"] < check["p50_kwh"] < check["p90_kwh"]
    assert str(round(TRUE_ANNUAL_KWH * 0.7)) in check["message"]


def test_a_meter_that_agrees_says_nothing(client: Any) -> None:
    """The band swallows a figure it does not contradict, and no constant said so."""
