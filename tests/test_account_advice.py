def test_the_check_is_never_written_into_a_shareable_advice(client: Any) -> None:
    """The line decision 63 draws, as an assertion.

    An advice is retrievable for ninety days by whoever holds its link. This
    household's real annual consumption is not something that link should
    carry, so the correction lives on a route that only answers the session
    that asked.
    """
    user = _register(client)
    _give_the_account_a_meter(user)
    advice = _advice(client)
    assert _check(client)["check"] is not None

    shared = client.get(f"/api/advice/{advice['token']}/").json()

    assert "consumption_check" not in shared
    assert "consumption_check" not in StoredAdvice.objects.get(token=advice["token"]).advice


def test_accepting_recomputes_on_the_measured_figure(client: Any) -> None:
    """The whole point of the route, and the assertion that could fail.

    The account typed 2800 and the meter was generated at 4000. An accept that
    quietly reused the typed figure would leave `entered_consumption_kwh` at
    2800, and an accept that took the proposal's word for it without refitting
    would still have to arrive at the same place.
    """
    user = _register(client)
    _give_the_account_a_meter(user)
    first = _advice(client)

    response = client.post(
        f"/api/auth/advice/{first['token']}/accept/",
        content_type="application/json",
        **_csrf(client),
    )

    assert response.status_code == 201, response.content
    body = response.json()
    assert body["token"] != first["token"]
    assert body["consumption_source"] == "MEASURED"
    assert body["confidence"] == "GOOD"
    # The year the answer was computed from. BODY carries no car and no heat
    # pump, so this is the accepted figure itself rather than it plus assets.
    assert body["modelled_consumption_kwh"]["value"] == pytest.approx(TRUE_ANNUAL_KWH, rel=0.02)
    assert first["modelled_consumption_kwh"]["value"] == pytest.approx(
        TRUE_ANNUAL_KWH * 0.7, rel=0.02
    )
    assert StoredAdvice.objects.get(token=body["token"]).owner == user


