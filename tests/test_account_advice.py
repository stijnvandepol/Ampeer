"""The two routes that let a household's own meter reach its own advice.

The meter is seeded by running the real model at a known annual consumption
and writing its grid flows in as readings. That is what makes the accepting
test evidence: the figure the route has to arrive at is one this file chose,
and it is thirty percent away from the figure the account typed.
"""

